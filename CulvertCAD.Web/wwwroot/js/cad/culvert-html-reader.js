// CulvertCAD — Generic 3D Culvert HTML Reader
// Extracts and normalizes 3D solid geometry (DATA / solidData) from CulvertCAD HTML exports.

(function (window) {
    "use strict";

    const CulvertHtmlReader = {
        /**
         * Parses an exported HTML File, Blob, or raw HTML string.
         * Extracts the embedded 3D solid geometry data.
         * @param {File|Blob|string} input - HTML File or string content.
         * @returns {Promise<Object>} Normalized solid model data { source, solidCount, solids, bounds }.
         */
        async parse(input) {
            let htmlText = "";

            if (typeof input === "string") {
                htmlText = input;
            } else if (input instanceof Blob || input instanceof File) {
                htmlText = await input.text();
            } else {
                throw new Error("Invalid input: expected an HTML File, Blob, or text string.");
            }

            if (!htmlText || htmlText.trim().length === 0) {
                throw new Error("The selected HTML file is empty.");
            }

            // Strategy 1: Targeted RegEx search for `const DATA = {...}` or `const solidData = {...}`
            const patterns = [
                /(?:const|let|var)\s+(?:DATA|solidData)\s*=\s*(\{[\s\S]*?\});(?:\s*(?:const|let|var|function|document|window|\n|<\/script>))/m,
                /(?:const|let|var)\s+(?:DATA|solidData)\s*=\s*(\{[\s\S]*?\n\s*\};)/m,
                /(?:window\.)?(?:CULVERT_TEST_SOLID_DATA|solidData|DATA)\s*=\s*(\{[\s\S]*?\});/m
            ];

            for (const pattern of patterns) {
                const match = htmlText.match(pattern);
                if (match && match[1]) {
                    try {
                        const parsed = this._evaluateData(match[1]);
                        if (this._isValidSolidData(parsed)) {
                            return this._normalize(parsed, input.name || "extracted-model.html");
                        }
                    } catch (err) {
                        console.warn("[CulvertHtmlReader] RegEx match evaluation failed:", err);
                    }
                }
            }

            // Strategy 2: DOMParser script element extraction fallback
            try {
                const doc = new DOMParser().parseFromString(htmlText, "text/html");
                const scripts = doc.querySelectorAll("script");

                for (const script of scripts) {
                    const text = script.textContent || "";
                    if (text.includes('"solids"') || text.includes("'solids'")) {
                        const firstBrace = text.indexOf("{");
                        const lastBrace = text.lastIndexOf("}");

                        if (firstBrace !== -1 && lastBrace > firstBrace) {
                            const jsonCandidate = text.substring(firstBrace, lastBrace + 1);
                            try {
                                const parsed = this._evaluateData(jsonCandidate);
                                if (this._isValidSolidData(parsed)) {
                                    return this._normalize(parsed, input.name || "extracted-model.html");
                                }
                            } catch (err) {
                                // continue to next script tag
                            }
                        }
                    }
                }
            } catch (domErr) {
                console.warn("[CulvertHtmlReader] DOMParser extraction failed:", domErr);
            }

            throw new Error(
                "No 3D culvert solid model data found. Ensure the file was generated by CulvertCAD and contains solid mesh geometry."
            );
        },

        /**
         * Safely evaluates raw JS object text or JSON.
         */
        _evaluateData(rawString) {
            const clean = rawString.trim().replace(/;$/, "");
            try {
                return JSON.parse(clean);
            } catch (jsonErr) {
                // If not strict JSON (e.g., JS object with unquoted keys), evaluate via scoped function
                return new Function(`"use strict"; return (${clean});`)();
            }
        },

        /**
         * Validates that the parsed data contains valid solids and geometry.
         */
        _isValidSolidData(data) {
            return (
                data &&
                typeof data === "object" &&
                Array.isArray(data.solids) &&
                data.solids.length > 0 &&
                data.solids.some(s => s.parts && s.parts.length > 0)
            );
        },

        /**
         * Normalizes fields (computes bounds, ensures colors, layer names, part counts).
         */
        _normalize(raw, fallbackName) {
            let totalParts = 0;
            let totalVertices = 0;
            let minX = Infinity, minY = Infinity, minZ = Infinity;
            let maxX = -Infinity, maxY = -Infinity, maxZ = -Infinity;

            const normalizedSolids = raw.solids.map((s, sIdx) => {
                const layer = s.layer || "Default";
                const handle = s.handle || String(sIdx + 1);
                const color = s.color || "#8b949e";
                const parts = (s.parts || []).map(p => {
                    totalParts++;
                    const vertices = p.vertices || [];
                    const faces = p.faces || [];
                    totalVertices += vertices.length;

                    // Compute bounding box
                    for (const v of vertices) {
                        if (v.length >= 3) {
                            if (v[0] < minX) minX = v[0];
                            if (v[0] > maxX) maxX = v[0];
                            if (v[1] < minY) minY = v[1];
                            if (v[1] > maxY) maxY = v[1];
                            if (v[2] < minZ) minZ = v[2];
                            if (v[2] > maxZ) maxZ = v[2];
                        }
                    }

                    return { vertices, faces };
                });

                return { handle, layer, color, parts };
            });

            return {
                source: raw.source || fallbackName,
                dxfVersion: raw.dxfVersion || "AutoCAD 3DSOLID",
                solidCount: normalizedSolids.length,
                partCount: totalParts,
                vertexCount: totalVertices,
                solids: normalizedSolids,
                bounds: {
                    min: [isFinite(minX) ? minX : 0, isFinite(minY) ? minY : 0, isFinite(minZ) ? minZ : 0],
                    max: [isFinite(maxX) ? maxX : 0, isFinite(maxY) ? maxY : 0, isFinite(maxZ) ? maxZ : 0]
                }
            };
        }
    };

    window.CulvertHtmlReader = CulvertHtmlReader;
})(window);